_BY_KEY = {n['key']: n for n in NOTES}


def _mmss(s):
    return '%d:%02d' % (s // 60, s % 60)


def _cum(key):
    t = 0
    for n in NOTES:
        if n['sec']:
            t += n['sec']
        if n['key'] == key:
            return t
    raise KeyError(key)


def _backup_lines(items):
    out = []
    for i, it in enumerate(items, 1):
        if isinstance(it, str):
            out.append(f'{i}. {it}')
        else:
            head, subs = it
            out.append(f'{i}. {head}')
            out += [f'   – {s}' for s in subs]
    return out


def render(key):
    """Notes text of one slide: the timed script, then the numbered backup items."""
    n = _BY_KEY[key]
    if n['sec']:
        head = f'【讲稿】约 {n["sec"]} 秒（本页结束时累计 {_mmss(_cum(key))}）'
    else:
        head = '【讲稿】备用页，被问到时再讲'
    return '\n'.join([head, n['script'], '', '【备查】'] + _backup_lines(n['backup']))


def total_seconds():
    return sum(n['sec'] for n in NOTES if n['sec'])


def export_markdown(path, numbers):
    """The whole script as Markdown; numbers maps a key to its slide number."""
    lines = ['# P1 NICE 组会汇报：讲稿与备查', '',
             f'由 `build_groupmeeting.py` 与幻灯片备注同时生成。讲稿合计约 {_mmss(total_seconds())}；上台只看【讲稿】，被问到时翻【备查】。', '']
    for n in NOTES:
        lines.append(f'## 第 {numbers[n["key"]]} 页　{n["title"]}')
        lines.append('')
        if n['sec']:
            lines.append(f'**【讲稿】约 {n["sec"]} 秒（本页结束时累计 {_mmss(_cum(n["key"]))}）**')
        else:
            lines.append('**【讲稿】备用页，被问到时再讲**')
        lines += ['', n['script'], '', '**【备查】**', '']
        for i, it in enumerate(n['backup'], 1):
            if isinstance(it, str):
                lines.append(f'{i}. {it}')
            else:
                head, subs = it
                lines.append(f'{i}. **{head}**')
                lines += [f'   - {s}' for s in subs]
        lines.append('')
    from pathlib import Path
    Path(path).write_text('\n'.join(lines), encoding='utf-8')
