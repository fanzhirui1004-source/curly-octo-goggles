    ap.add_argument('--model', default='net', choices=['net', 'free', 'free_unbounded', 'free_coarse'], help='free: free coefficients under the network head bounds; free_coarse: free band + coarse-space compliance G = exp(H); single label, no augmentation')
    ap.add_argument('--coarse-stride', type=int, default=4); ap.add_argument('--coarse-prune', type=float, default=0.05); ap.add_argument('--coarse-init', default='teacher', choices=['teacher', 'identity'])
    ap.add_argument('--seats', default=None, help='comma-separated seats to train on (subset of the label file)')
    args = ap.parse_args()
    out = Path(args.output); out.mkdir(parents=True, exist_ok=False); t_start = time.perf_counter(); torch.manual_seed(args.seed)
    write_json(out / 'PROTOCOL.json', dict(vars(args), schema='CUTFEM_SUPERELEMENT_V1', script_sha256=V0.sha256(__file__)))
    records = json.load(open(args.labels))
    train_recs = [r for r in records if r['split'] == 'train' and r['q'] <= args.train_max_q][:args.max_train_labels]; val_recs = [r for r in records if r['split'] != 'train' and r['q'] <= args.train_max_q]
    if args.seats:                                                       # explicit seats: trained regardless of split (a known-label diagnostic, recorded as such)
        keep = {int(x) for x in args.seats.split(',')}; train_recs = [r for r in records if int(r['seat']) in keep]; val_recs = []
    if args.model != 'net': assert len(train_recs) == 1 and args.aug_prob == 0, 'free coefficients: one training label, no augmentation'
    print(json.dumps(dict(stage='labels', train=[r['seat'] for r in train_recs], validation=[r['seat'] for r in val_recs])), flush=True)
    labels = {int(r['seat']): Label(r, args.r_near, args.decay, args.off_scale) for r in train_recs + val_recs}
    for l in labels.values(): l.tri_mode = args.tri_solver if args.tri_solver != 'auto' else ('dense' if l.q <= args.dense_max_q else 'sparse')
    print(json.dumps(dict(stage='prepared', seconds=time.perf_counter() - t_start, q={s: l.q for s, l in labels.items()})), flush=True)
    first = labels[int(train_recs[0]['seat'])]
    if args.model == 'free_coarse':
        Pq = first.coarse_basis(args.coarse_stride, args.coarse_prune); net = FreeCoarseModel(first, args.off_scale, Pq.shape[1]).to(DEV)
        print(json.dumps(dict(stage='coarse_basis', stride=args.coarse_stride, prune=args.coarse_prune, columns=int(Pq.shape[1]))), flush=True)
    else:
        net = (FreeCoefficientModel(first, args.rank, args.off_scale) if args.model == 'free' else FreeUnboundedModel(first, args.rank, args.off_scale) if args.model == 'free_unbounded'
               else GeometryNet(first.images.shape[1], args.width, args.rank, args.hidden, off_scale=args.off_scale, volume_width=args.volume_width)).to(DEV)
    group = cube_group()
    if args.model == 'free_coarse':                                        # band from a network checkpoint if given, coarse compliance from the teacher (or identity)
        g0 = first.to_gpu(need_A=False, need_Z=True, z_dtype=torch.float64); log_w0 = g0['w'].log()
        if args.init_checkpoint:
            ref = GeometryNet(first.images.shape[1], args.width, args.rank, args.hidden, off_scale=args.off_scale, volume_width=args.volume_width).to(DEV)
            ref.load_state_dict(torch.load(args.init_checkpoint, map_location='cuda')['net']); ref.eval(); net.from_network(ref, g0); del ref
        with torch.no_grad():
            values0 = bounded_band(net.dg, net.pair_p, g0, log_w0, args.off_scale)
            info = net.init_coarse_from_teacher(g0, values0) if args.coarse_init == 'teacher' else {}
            v_free, M_free = net(g0, log_w0); D0 = divergence_terms(g0, Operator(g0, v_free, M_free), torch.float64)[0] / g0['d']
        check = dict(stage='free_coarse_init', seat=first.seat, checkpoint=args.init_checkpoint, columns=int(g0['Pq'].shape[1]), divergence_per_mode_init=float(D0), **info)
        print(json.dumps(check), flush=True); write_json(out / 'FREE_INIT_CHECK.json', check); del g0, v_free, M_free; first.release(); torch.cuda.empty_cache()
    elif args.init_checkpoint and args.model in ('free', 'free_unbounded'):   # free coefficients start from the network's own prediction for this label (original frame)
        ref = GeometryNet(first.images.shape[1], args.width, 512, args.hidden, off_scale=args.off_scale, volume_width=args.volume_width).to(DEV)
        ref.load_state_dict(torch.load(args.init_checkpoint, map_location='cuda')['net']); ref.eval()
        g0 = first.to_gpu(need_A=False, need_Z=True, z_dtype=torch.float64); log_w0 = g0['w'].log()
        with torch.no_grad():
            net.from_network(ref, g0); v_ref, M_ref = ref(g0, log_w0); v_free, M_free = net(g0, log_w0)
            D_ref = divergence_terms(g0, Operator(g0, v_ref, M_ref), torch.float64)[0] / g0['d']; D_free = divergence_terms(g0, Operator(g0, v_free, M_free), torch.float64)[0] / g0['d']
        check = dict(stage='free_init', seat=first.seat, checkpoint=args.init_checkpoint, values_max_rel_diff=float((v_ref - v_free).abs().max() / v_ref.abs().max()),
                     M_max_rel_diff=float((M_ref[:, :min(M_ref.shape[1], M_free.shape[1])] - M_free[:, :min(M_ref.shape[1], M_free.shape[1])]).abs().max() / M_ref.abs().max()), divergence_per_mode_net=float(D_ref), divergence_per_mode_free=float(D_free))
        print(json.dumps(check), flush=True); write_json(out / 'FREE_INIT_CHECK.json', check); del ref, g0, v_ref, M_ref, v_free, M_free; first.release(); torch.cuda.empty_cache()
    elif args.init_checkpoint: net.load_state_dict(torch.load(args.init_checkpoint, map_location='cuda')['net'])
    nparam = sum(p.numel() for p in net.parameters()); write_json(out / 'MODEL.json', dict(parameters=nparam, model=str(net)))
    print(json.dumps(dict(stage='setup', parameters=nparam)), flush=True)
    opt = torch.optim.Adam(net.parameters(), lr=args.lr)
    gen = torch.Generator(device=DEV).manual_seed(args.seed + 1)
    eval_train = [l for l in labels.values() if (args.seats or l.record['split'] == 'train') and l.q <= args.eval_max_q][:args.eval_labels]
    eval_val = [l for l in labels.values() if not args.seats and l.record['split'] != 'train' and l.q <= args.eval_max_q][:args.eval_labels]
    probe_objective = args.energy_weight > 0 or args.action_weight > 0 or args.dual_weight > 0 or args.compliance_weight > 0
    exact_objective = args.divergence_weight > 0 or args.extreme_weight > 0
    z_dtype = torch.float32 if args.trace_dtype == 'float32' else torch.float64
    def run_eval(step):
        rows = []
        for l in eval_train + eval_val:
            g = l.to_gpu(need_A=False, need_Z=True, z_dtype=torch.float32); res = evaluate_spectral(l, g, net, args.seed)
            del g; l.release(); torch.cuda.empty_cache()
            if args.eval_dense:
                g = l.to_gpu(need_A=True, need_Z=False); res.update(evaluate_label(l, g, net, args.seed)); del g; l.release(); torch.cuda.empty_cache()
            else: res['evaluation_seconds'] = res['spectral_seconds']
            res['step'] = step; res['split'] = l.record['split'] if not args.seats else 'known-label'; rows.append(res)
            print(json.dumps(dict(stage='evaluation', step=step, split=res['split'], **brief(res))), flush=True)
        write_json(out / f'EVALUATION_{step:06d}.json', json_finite(rows)); return rows
    evaluations = [run_eval(0)]
    step = 0; order = list(labels[int(r['seat'])] for r in train_recs); rng = np.random.default_rng(args.seed)
    history = []
    while step < args.steps:
        rng.shuffle(order)
        for l in order:
            if step >= args.steps: break
            g = l.to_gpu(need_A=probe_objective, need_Z=exact_objective, z_dtype=z_dtype); log_w = g['w'].log()
            for _ in range(args.chunk):
                if step >= args.steps: break
                step += 1; tick = sync()
                sched = min(1.0, step / args.warmup) * (args.lr_floor + (1 - args.lr_floor) * 0.5 * (1 + math.cos(math.pi * (step - 1) / max(args.steps - 1, 1))))
                for g_ in opt.param_groups: g_['lr'] = args.lr * sched
                opt.zero_grad(set_to_none=True)
                try:
                    if args.aug_prob > 0 and rng.random() < args.aug_prob:
                        perm, sign = group[int(rng.integers(1, len(group)))]
                        ga = dict(g); ga.update(l.transformed(perm, sign))
                    else: ga = g
                    values, M = net(ga, log_w); op = Operator(ga, values, M)
                    loss_e = loss_a = loss_d = loss_c = loss_D = loss_x = torch.zeros((), dtype=torch.float64, device=DEV); ritz = None
                    if args.energy_weight > 0:
                        z = draw_probes(g, args.probes, args.white_probes, gen); loss_e = energy_error(g, op, z).mean()
                    if args.action_weight > 0:
                        zw = torch.randn(g['A'].shape[0], args.action_probes, dtype=torch.float64, device=DEV, generator=gen); loss_a = action_error(g, op, zw).mean()
                    residual = 0.0
                    if args.divergence_weight > 0:
                        D, trace, gap, residual = divergence_terms(g, op, z_dtype, args.solve_tol); loss_D = D / g['d']
                    if args.extreme_weight > 0 and residual <= args.solve_tol:
                        loss_x, ritz = extreme_terms(g, op, args.extreme_iters, args.extreme_block, gen)
                    if args.dual_weight > 0 and step >= args.dual_start:
                        e_disp, e_comp = dual_error(g, op, args.dual_probes, gen, kind=args.dual_kind)
                        loss_d = (torch.log1p(e_disp) if args.dual_log else e_disp.clamp(max=args.dual_clip)).mean()
                        loss_c = e_comp.clamp(max=args.dual_clip).mean()
                except torch._C._LinAlgError as err:
                    print(json.dumps(dict(stage='guard', step=step, seat=l.seat, reason=repr(err)[:120])), flush=True); continue
                w_e = min(1.0, step / max(args.energy_ramp, 1))
                loss = args.energy_weight * w_e * loss_e + args.action_weight * loss_a + args.dual_weight * loss_d + args.compliance_weight * loss_c + args.divergence_weight * loss_D + args.extreme_weight * loss_x
                if not torch.isfinite(loss):
                    print(json.dumps(dict(stage='guard', step=step, seat=l.seat)), flush=True); continue
                loss.backward(); gn = torch.nn.utils.clip_grad_norm_(net.parameters(), 10.0)
                if not torch.isfinite(gn):
                    opt.zero_grad(set_to_none=True); print(json.dumps(dict(stage='guard', step=step, seat=l.seat, reason='nonfinite gradient')), flush=True); continue
                opt.step()
                row = dict(step=step, seat=l.seat, lr=args.lr * sched, loss=float(loss.detach()), energy_loss=float(loss_e.detach()), action_loss=float(loss_a.detach()), dual_loss=float(loss_d.detach()), compliance_loss=float(loss_c.detach()), grad_norm=float(gn), seconds=sync() - tick)
                if args.divergence_weight > 0: row.update(divergence_per_mode=float(loss_D.detach()), trace_per_mode=float(trace.detach()) / label_d(g), logdet_gap=float(gap.detach()), solve_residual=residual, ill_conditioned=int(residual > args.solve_tol), augmented=int(ga is not g))
                if ritz is not None: row.update(extreme_loss=float(loss_x.detach()), ritz_max=float(ritz.detach().max()), ritz_min=float(ritz.detach().min()))
                history.append(row); append_json(out / 'HISTORY.jsonl', row)
                if step <= 5 or step % 50 == 0:
                    print(json.dumps(dict(**row, mean_loss_200=float(np.mean([r['loss'] for r in history[-200:]])), elapsed=time.perf_counter() - t_start, peak_gib=torch.cuda.max_memory_allocated() / 2**30)), flush=True)
                if step % args.eval_every == 0 or step == args.steps:
                    torch.save(dict(net=net.state_dict(), step=step), out / f'CHECKPOINT_{step:06d}.pt')
                    l.store_extremes(g); del g, op, values, M; l.release(); torch.cuda.empty_cache()
                    evaluations.append(run_eval(step))
                    g = l.to_gpu(need_A=probe_objective, need_Z=exact_objective, z_dtype=z_dtype); log_w = g['w'].log()
            l.store_extremes(g); del g; l.release(); torch.cuda.empty_cache()
    write_json(out / 'RESULT.json', json_finite(dict(status='COMPLETED_FIXED_BUDGET', steps=args.steps, elapsed_seconds=time.perf_counter() - t_start, parameters=nparam,
                                                    peak_gpu_allocated_gib=torch.cuda.max_memory_allocated() / 2**30, initial=evaluations[0], final=evaluations[-1])))
    print(json.dumps(dict(stage='done', elapsed=time.perf_counter() - t_start)), flush=True)


