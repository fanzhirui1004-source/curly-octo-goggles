class ResBlock(nn.Module):
    def __init__(self, c, dilation):
        super().__init__()
        self.c1 = nn.Conv2d(c, c, 3, padding=dilation, dilation=dilation); self.c2 = nn.Conv2d(c, c, 3, padding=1)
        self.norm = nn.GroupNorm(8, c)
    def forward(self, x):
        return x + self.c2(F.silu(self.c1(F.silu(self.norm(x)))))


class VolumeNet(nn.Module):
    """Coarse 3D branch on the 33^3 analytic field; features sampled at the face nodes feed the mode head."""
    def __init__(self, c_in=11, width=32):
        super().__init__()
        self.net = nn.Sequential(nn.Conv3d(c_in, 16, 3, padding=1), nn.SiLU(), nn.Conv3d(16, width, 3, stride=2, padding=1), nn.SiLU(),
                                 nn.Conv3d(width, width, 3, padding=1), nn.SiLU(), nn.Conv3d(width, width, 3, padding=1))
        self.width = width
    def forward(self, volume, xyz):
        f = self.net(volume[None])                                            # (1, C, 17, 17, 17)
        pts = (2 * xyz[:, [2, 1, 0]] - 1)[None, :, None, None]                # grid_sample takes z,y,x order
        return F.grid_sample(f, pts, mode='bilinear', align_corners=True, padding_mode='border')[0, :, :, 0, 0].T    # (n, C)


class GeometryNet(nn.Module):
    def __init__(self, c_in, width=64, rank=512, hidden=128, dilations=(1, 2, 4, 8), off_scale=OFF_SCALE, volume_width=32):
        super().__init__()
        self.width, self.rank, self.off_scale = width, rank, off_scale
        self.volume = VolumeNet(11, volume_width) if volume_width else None
        self.vol_norm = nn.LayerNorm(volume_width) if volume_width else None
        self.stem = nn.Conv2d(c_in, width, 3, padding=1)
        self.blocks = nn.ModuleList([ResBlock(width, dl) for dl in dilations])
        self.context = nn.Sequential(nn.Linear(width + 12, width), nn.SiLU(), nn.Linear(width, width))
        self.node_norm = nn.LayerNorm(width)
        self.diag = nn.Sequential(nn.Linear(width, hidden), nn.SiLU(), nn.Linear(hidden, 6))          # 3 log-diag corrections + 3 in-block off values
        self.pair = nn.Sequential(nn.Linear(2 * width + 4 + 12, hidden), nn.SiLU(), nn.Linear(hidden, hidden), nn.SiLU(), nn.Linear(hidden, 9))
        self.mode = nn.Sequential(nn.Linear(width + (volume_width or 0), hidden), nn.SiLU(), nn.Linear(hidden, 3 * rank))
        self.mode_logscale = nn.Parameter(torch.full((rank,), math.log(0.03)))
        for head in (self.diag, self.pair, self.mode):
            nn.init.normal_(head[-1].weight, std=1e-2); nn.init.zeros_(head[-1].bias)

    def node_features(self, g):
        x = self.stem(g['images'])
        for b in self.blocks: x = b(x)
        ctx = self.context(torch.cat((x.mean(dim=(0, 2, 3)), g['theta'])))
        flat = x.flatten(2)                                                  # (6, C, 65*65)
        feats = flat[g['mem_face'], :, g['mem_pix']]                         # (memberships, C)
        n = int(g['face_of_node'].shape[0])
        h = torch.zeros((n, self.width), device=DEV, dtype=feats.dtype).index_add_(0, g['mem_node'], feats)
        cnt = torch.zeros(n, device=DEV, dtype=feats.dtype).index_add_(0, g['mem_node'], torch.ones_like(feats[:, 0]))
        return self.node_norm(h / cnt[:, None] + ctx[None, :])

    def preactivations(self, g):
        """Head outputs before the bounded maps: dg (n, 6), pair (npair, 9), mode (n, 3 rank)."""
        h = self.node_features(g)
        fi = F.one_hot(g['face_of_node'], 6).float(); pi, pj = g['pair_i'], g['pair_j']
        inp = torch.cat((h[pi], h[pj], 5.0 * g['pair_dx'], (g['face_of_node'][pi] == g['face_of_node'][pj]).float()[:, None], fi[pi], fi[pj]), dim=1)
        hm = torch.cat((h, self.vol_norm(self.volume(g['volume'], g['xyz']))), dim=1) if self.volume is not None else h
        return self.diag(h), self.pair(inp), self.mode(hm)

    def forward(self, g, log_w):
        """Returns band COO values (sorted order, float64) and M (q x rank, float64).
        Off-diagonal band entries are bounded by the smaller of the two diagonals they connect, times a distance prior,
        so every row of L stays within a bounded ratio of its diagonal and the triangular solves stay stable."""
        dg, pair, mode = self.preactivations(g)
        return bounded_values(dg.double(), pair.double(), mode.double(), self.mode_logscale.double(), g, log_w, self.rank, self.off_scale)


def bounded_values(dg, pair, mode, mode_logscale, g, log_w, rank, off_scale):
    """The bounded maps shared by the geometry network and the free-coefficient model (all float64):
    diag = sqrt(S0 w) exp(3 tanh(dg/3)); in-block and pair entries = tanh(.) min(D_i, D_j) off_scale [exp(-d/decay)]; M = 0.1 tanh(.) exp(logscale)."""
    values = bounded_band(dg, pair, g, log_w, off_scale)
    M = (0.1 * torch.tanh(mode)).view(-1, rank) * mode_logscale.exp()[None, :]
    return values, M


def bounded_band(dg, pair, g, log_w, off_scale):
    n = dg.shape[0]
    logdiag = math.log(S0) * 0.5 + 0.5 * log_w[:, None] + 3.0 * torch.tanh(dg[:, :3] / 3.0); D = logdiag.exp()
    ua, ub = torch.triu_indices(3, 3, device=DEV); is_d = ua == ub
    dvals = torch.empty((n, 6), dtype=torch.float64, device=DEV)
    dvals[:, is_d] = D; dvals[:, ~is_d] = off_scale * torch.minimum(D[:, ua[~is_d]], D[:, ub[~is_d]]) * torch.tanh(dg[:, 3:])
    pi, pj = g['pair_i'], g['pair_j']; dmin = torch.minimum(D[pi][:, :, None], D[pj][:, None, :]).reshape(-1, 9)
    blocks = torch.tanh(pair) * dmin * (off_scale * g['pair_decay'])[:, None]
    return torch.cat((blocks.reshape(-1), dvals.reshape(-1)))[g['band_perm']]


class FreeCoefficientModel(nn.Module):
    """Free coefficients through exactly the same bounded maps as the GeometryNet heads (pre-activations become parameters).
    Single label, no symmetry frames: a capacity test of the representation under the network's feasible set."""
    def __init__(self, label, rank=512, off_scale=OFF_SCALE):
        super().__init__(); self.rank, self.off_scale = rank, off_scale
        self.dg = nn.Parameter(torch.zeros(label.nn, 6, dtype=torch.float64)); self.pair_p = nn.Parameter(torch.zeros(len(label.pair_i), 9, dtype=torch.float64))
        self.mode_p = nn.Parameter(1e-2 * torch.randn(label.nn, 3 * rank, dtype=torch.float64)); self.mode_logscale = nn.Parameter(torch.full((rank,), math.log(0.03), dtype=torch.float64))
    @torch.no_grad()
    def from_network(self, net, g):
        dg, pair, mode = net.preactivations(g)
        self.dg.copy_(dg.double()); self.pair_p.copy_(pair.double()); self.mode_p.copy_(mode.double()); self.mode_logscale.copy_(net.mode_logscale.double())
        return self
    def forward(self, g, log_w):
        return bounded_values(self.dg, self.pair_p, self.mode_p, self.mode_logscale, g, log_w, self.rank, self.off_scale)


class FreeUnboundedModel(nn.Module):
    """Free band coefficients (network head bounds) plus a free, unbounded M (q x rank): the representation class itself, no head bound on M."""
    def __init__(self, label, rank=1024, off_scale=OFF_SCALE):
        super().__init__(); self.rank, self.off_scale = rank, off_scale
        self.dg = nn.Parameter(torch.zeros(label.nn, 6, dtype=torch.float64)); self.pair_p = nn.Parameter(torch.zeros(len(label.pair_i), 9, dtype=torch.float64))
        self.M = nn.Parameter(1e-3 * torch.randn(label.q, rank, dtype=torch.float64))
    @torch.no_grad()
    def from_network(self, net, g):
        dg, pair, mode = net.preactivations(g); self.dg.copy_(dg.double()); self.pair_p.copy_(pair.double())
        Mn = (0.1 * torch.tanh(mode.double())).view(-1, net.rank) * net.mode_logscale.exp().double()[None, :]; k = min(net.rank, self.rank)
        self.M[:, :k].copy_(Mn[:, :k]); self.M[:, k:].mul_(float(Mn.abs().mean())); return self
    def forward(self, g, log_w):
        return bounded_band(self.dg, self.pair_p, g, log_w, self.off_scale), self.M


class FreeCoarseModel(nn.Module):
    """Free band coefficients (same bounded maps as the network heads) plus a coarse-space compliance:
    K0^-1 = L^-1 L^-T + Pq G Pq^T with G = C C^T, C lower triangular with positive diagonal (free k x k) on the orthonormal
    coarse basis Pq; M = L Pq C. Cholesky-type parameterization: unique, positive definite, no eigen-decomposition in the graph."""
    def __init__(self, label, off_scale=OFF_SCALE, k=None):
        super().__init__(); self.off_scale = off_scale; self.k = k
        self.dg = nn.Parameter(torch.zeros(label.nn, 6, dtype=torch.float64)); self.pair_p = nn.Parameter(torch.zeros(len(label.pair_i), 9, dtype=torch.float64))
        self.C_raw = nn.Parameter(torch.zeros(k, k, dtype=torch.float64))
    @torch.no_grad()
    def from_network(self, net, g):
        dg, pair, _ = net.preactivations(g); self.dg.copy_(dg.double()); self.pair_p.copy_(pair.double()); return self
    def C(self):
        return torch.tril(self.C_raw, -1) + torch.diag(self.C_raw.diagonal().exp())
    def logdet_G(self): return 2.0 * float(self.C_raw.diagonal().sum())
    def forward(self, g, log_w):
        values = bounded_band(self.dg, self.pair_p, g, log_w, self.off_scale)
        q = g['Pq'].shape[0]; L = torch.sparse_coo_tensor(g['band_index'], values, (q, q), is_coalesced=True)
        return values, torch.sparse.mm(L, g['Pq'] @ self.C())
    @torch.no_grad()
    def init_coarse_from_teacher(self, g, values, floor=1e-4):
        """G = Pq^T (A^-1 - L^-1 L^-T) Pq on the quotient, eigenvalues floored at floor x the teacher's coarse compliance scale."""
        Pq = g['Pq']; q = Pq.shape[0]
        Zc = torch.linalg.solve_triangular(g['Rstar'].T, g['data'].quotient(Pq), upper=False); Gt = Zc.T @ Zc; del Zc            # coarse teacher compliance
        Ld = torch.sparse_coo_tensor(g['band_index'], values, (q, q), is_coalesced=True).to_dense()
        X = torch.linalg.solve_triangular(Ld.T, Pq, upper=False); del Ld; Gl = X.T @ X; del X                                   # coarse local compliance
        lam, U = torch.linalg.eigh(Gt - Gl); scale = float(torch.linalg.eigvalsh(Gt).max()); floored = int((lam < floor * scale).sum()); lam = lam.clamp(min=floor * scale)
        Cc = torch.linalg.cholesky((U * lam[None, :]) @ U.T)
        self.C_raw.copy_(torch.tril(Cc, -1) + torch.diag(Cc.diagonal().log()))
        return dict(coarse_teacher_compliance_max=scale, coarse_local_compliance_max=float(torch.linalg.eigvalsh(Gl).max()), floored=floored)


class BandTriSolve(torch.autograd.Function):
    """Solve L X = B (upper=True) or L^T X = B (upper=False) for the banded upper-triangular L given by COO (index, values).
    mode='dense': cuBLAS trsm on a dense copy of L (fast, q^2 memory, rebuilt in backward).
    mode='sparse': cuSPARSE CSR triangular solve (no q^2 memory, slower on long dependency chains).
    Backward computes the gradient only on the band."""
    @staticmethod
    def solve(values, B, index, crow, q, upper, mode):
        if mode == 'sparse':
            csr = torch.sparse_csr_tensor(crow, index[1], values, (q, q))
            return torch.triangular_solve(B, csr, upper=True, transpose=not upper)[0]
        L = torch.sparse_coo_tensor(index, values, (q, q), is_coalesced=True).to_dense()
        return torch.linalg.solve_triangular(L if upper else L.T, B, upper=upper)
    @staticmethod
    def forward(ctx, values, B, index, crow, q, upper, mode):
        X = BandTriSolve.solve(values.detach(), B, index, crow, q, upper, mode)
        ctx.save_for_backward(values.detach(), X, index, crow); ctx.q, ctx.upper, ctx.mode = q, upper, mode
        return X
    @staticmethod
    def backward(ctx, dX):
        values, X, index, crow = ctx.saved_tensors; q, upper, mode = ctx.q, ctx.upper, ctx.mode
        # X = L^-1 B:  dB = L^-T dX,  dL[i,j] = -(L^-T dX)_i . X_j ;   X = L^-T B:  dB = L^-1 dX,  dL[i,j] = -X_i . (L^-1 dX)_j
        Y = BandTriSolve.solve(values, dX, index, crow, q, not upper, mode)
        I, J = index[0], index[1]; g = torch.empty(I.shape[0], dtype=values.dtype, device=values.device)
        for b in range(0, I.shape[0], 2_000_000):
            i, j = I[b:b + 2_000_000], J[b:b + 2_000_000]
            g[b:b + 2_000_000] = -((Y[i] * X[j]).sum(1) if upper else (X[i] * Y[j]).sum(1))
        return g, Y, None, None, None, None, None


class Operator:
    """S_hat = L^T (I + M M^T)^-1 L, applied by Woodbury with G = I + M^T M."""
    def __init__(self, g, values, M):
        self.q = int(M.shape[0]); self.values = values; self.index = g['band_index']; self.crow = g['band_crow']; self.tri_mode = g.get('tri_mode', 'dense')
        Q = g.get('Q'); self.Q = None if Q is None or bool(torch.equal(Q, torch.eye(3, dtype=Q.dtype, device=Q.device))) else Q
        self.L = torch.sparse_coo_tensor(g['band_index'], values, (self.q, self.q), is_coalesced=True)
        self.LT = torch.sparse_coo_tensor(g['band_index_t'], values, (self.q, self.q)); self.M = M
        G = M.T @ M; G.diagonal().add_(1.0); self.C = torch.linalg.cholesky(G)
    def pi(self, x, inverse=False):
        """Apply Pi = I (x) Q (or its transpose) to node-major vectors: original frame <-> transformed frame."""
        if self.Q is None: return x
        X = x.reshape(-1, 3, x.shape[1]); Qm = (self.Q.T if inverse else self.Q).to(x.dtype)
        return torch.einsum('ab,nbm->nam', Qm, X).reshape(x.shape)
    def apply(self, x):
        x = self.pi(x)
        u = torch.sparse.mm(self.L, x); t = self.M.T @ u
        u = u - self.M @ torch.cholesky_solve(t, self.C)
        return self.pi(torch.sparse.mm(self.LT, u), inverse=True)
    def restricted_inverse(self, quotient, rigid, y):
        """x_hat = (B S_hat B^T)^-1 y via full-space solves S_hat^-1 = L^-1 (I + M M^T) L^-T and a rank-6 rigid correction."""
        Fm = self.pi(torch.cat((quotient.lift(y), rigid), dim=1))
        Z = BandTriSolve.apply(self.values, Fm, self.index, self.crow, self.q, False, self.tri_mode); Z = Z + self.M @ (self.M.T @ Z)
        U = self.pi(BandTriSolve.apply(self.values, Z, self.index, self.crow, self.q, True, self.tri_mode), inverse=True); m = y.shape[1]; UF, UN = U[:, :m], U[:, m:]
        return quotient(UF - UN @ torch.linalg.solve(rigid.T @ UN, rigid.T @ UF))
    def solve_full(self, Y):
        """S_hat^-1 Y on the full face space (no rigid correction), in the original frame."""
        Z = BandTriSolve.apply(self.values, self.pi(Y), self.index, self.crow, self.q, False, self.tri_mode); Z = Z + self.M @ (self.M.T @ Z)
        return self.pi(BandTriSolve.apply(self.values, Z, self.index, self.crow, self.q, True, self.tri_mode), inverse=True)
    @torch.no_grad()
    def materialize(self):
        Y = torch.linalg.solve_triangular(self.C, self.M.T, upper=False)
        T = -(Y.T @ Y); del Y; T.diagonal().add_(1.0)
        Q1 = torch.sparse.mm(self.LT, T); del T
        S = torch.sparse.mm(self.LT, Q1.T.contiguous()); del Q1
        S = 0.5 * (S + S.T)
        if self.Q is not None:                                                # back to the original frame: Pi^T S' Pi
            S = self.pi(self.pi(S, inverse=True).T, inverse=True).T
        return S


# ----------------------------------------------------------------------------- probes, loss, evaluation
def draw_probes(g, m, white, generator):
    q, d = g['P3'].shape[0], g['A'].shape[0]; mc = m // 2
    zc = torch.randn(g['P3'].shape[1], mc, dtype=torch.float64, device=DEV, generator=generator)
    xf = torch.randn(q, m - mc, dtype=torch.float64, device=DEV, generator=generator) * g['wq'].sqrt()[:, None]
    z = g['data'].quotient(torch.cat((g['P3'] @ zc, xf), dim=1))
    if white:
        xi = torch.randn(d, white, dtype=torch.float64, device=DEV, generator=generator)
        z = torch.cat((z, torch.linalg.solve_triangular(g['Rstar'], xi, upper=True)), dim=1)
    return z


def energy_error(g, op, z):
    ref = g['A'] @ z; pred = g['data'].quotient(op.apply(g['data'].quotient.lift(z)))
    return torch.linalg.solve_triangular(g['Rstar'].T, pred - ref, upper=False).square().sum(0) / (g['Rstar'] @ z).square().sum(0)


def dual_error(g, op, m, generator, kind='white'):
    """Inverse (response) error. kind='white': forces uniform over modes in the energy metric.
    kind='physical': support-weighted smooth tractions (half) and support-weighted random balanced loads (half).
    Returns (energy-norm relative displacement error, relative compliance error) per probe."""
    R = g['Rstar']; d = g['A'].shape[0]
    if kind == 'white':
        xi = torch.randn(d, m, dtype=torch.float64, device=DEV, generator=generator); y = R.T @ xi
        xr = torch.linalg.solve_triangular(R, xi, upper=True)
    else:
        q = g['P3'].shape[0]; mc = m // 2
        zc = torch.randn(g['P3'].shape[1], mc, dtype=torch.float64, device=DEV, generator=generator)
        xf = torch.randn(q, m - mc, dtype=torch.float64, device=DEV, generator=generator)
        y = g['data'].quotient(g['wq'][:, None] * torch.cat((g['P3'] @ zc, xf), dim=1))
        xr = torch.linalg.solve_triangular(R, torch.linalg.solve_triangular(R.T, y, upper=False), upper=True)
    xh = op.restricted_inverse(g['data'].quotient, g['rigid'], y)
    e_disp = (R @ (xh - xr)).square().sum(0) / (R @ xr).square().sum(0)
    e_comp = ((y * xh).sum(0) - (y * xr).sum(0)).abs() / (y * xr).sum(0).abs()
    return e_disp, e_comp


# ----------------------------------------------------------------------------- probe-free objective: log-det divergence + extreme whitened modes
def divergence_terms(g, op, trace_dtype=torch.float32, solve_tol=1e-6):
    """Exact log-det divergence of the student against the teacher, D = tr(A^-1 A_hat) - log det(A^-1 A_hat) - d = sum_i (mu_i - log mu_i - 1)
    over the whitened spectrum mu of R*^-T A_hat R*^-1.  No probes:
      tr(A^-1 A_hat) = ||(I + M M^T)^-1/2 L Pi Z^T||_F^2 with Z = R*^-T B (Pi: augmentation frame),
      log det A_hat  = 2 sum log L_ii - log det(I + M^T M) + log det(N^T S_hat^-1 N) - log det(N^T N)   (orthonormal rigid quotient B).
    The trace is evaluated in trace_dtype (float32 is enough for its gradient); the value logged is exact up to that rounding.
    Returns (D, trace, log-det gap, solve residual). When the rigid-correction solve residual exceeds solve_tol the step is numerically
    unreliable: the rigid term is dropped (gap then lacks a per-label constant) so that no gradient flows through the ill-conditioned solve."""
    ZT = op.pi(g['ZT']).to(trace_dtype)
    L = torch.sparse_coo_tensor(op.index, op.values.to(trace_dtype), (op.q, op.q), is_coalesced=True)
    T = torch.sparse.mm(L, ZT)                                                                          # (q, d)
    Y = torch.linalg.solve_triangular(op.C.to(trace_dtype), op.M.to(trace_dtype).T @ T, upper=False)   # C^-1 M^T T
    trace = (T.square().sum() - Y.square().sum()).double(); del T, Y
    logdet_S = 2.0 * op.values[g['band_is_diag']].log().sum() - 2.0 * op.C.diagonal().log().sum()
    N = g['rigid']; U = op.solve_full(N)
    with torch.no_grad(): residual = float(torch.linalg.matrix_norm(op.apply(U) - N) / torch.linalg.matrix_norm(N))   # K0 U = N solve residual
    if residual > solve_tol:                                                                             # ill-conditioned K0: keep only the solve-free part
        return trace - (logdet_S - g['logdet_A']) - g['d'], trace, logdet_S - g['logdet_A'], residual
    logdet_hat = logdet_S + torch.logdet(N.T @ U) - g['logdet_NtN']
    gap = logdet_hat - g['logdet_A']
    return trace - gap - g['d'], trace, gap, residual


@torch.no_grad()
def factor_conditioning(op, iters=30):
    """Estimates of sigma_max(L), sigma_min(L) (power / inverse iteration on L^T L) and ||M||_2; K0 is bounded by
    sigma_min(L)^2 / (1 + ||M||^2) <= K0 <= sigma_max(L)^2."""
    q = op.q; v = torch.randn(q, 1, dtype=torch.float64, device=DEV); v /= v.norm()
    for _ in range(iters):
        v = torch.sparse.mm(op.LT, torch.sparse.mm(op.L, v)); smax = v.norm().sqrt(); v /= v.norm()
    v = torch.randn(q, 1, dtype=torch.float64, device=DEV); v /= v.norm()
    Ld = torch.sparse_coo_tensor(op.index, op.values, (q, q), is_coalesced=True).to_dense()
    for _ in range(iters):
        v = torch.linalg.solve_triangular(Ld, torch.linalg.solve_triangular(Ld.T, v, upper=False), upper=True); smin = 1.0 / v.norm().sqrt(); v /= v.norm()
    del Ld
    mnorm = torch.linalg.eigvalsh(op.M.T @ op.M).max().sqrt()
    return dict(L_sigma_max=float(smax), L_sigma_min=float(smin), M_norm=float(mnorm), K0_condition_bound=float(smax ** 2 * (1 + mnorm ** 2) / smin ** 2))


def whiten_apply(g, op, V):
    """W V with W = R*^-T (B S_hat B^T) R*^-1 (differentiable through the student)."""
    X = torch.linalg.solve_triangular(g['Rstar'], V, upper=True)
    Y = g['data'].quotient(op.apply(g['data'].quotient.lift(X)))
    return torch.linalg.solve_triangular(g['Rstar'].T, Y, upper=False)


def whiten_solve(g, op, V):
    """W^-1 V = R* (B S_hat B^T)^-1 R*^T V."""
    return g['Rstar'] @ op.restricted_inverse(g['data'].quotient, g['rigid'], g['Rstar'].T @ V)


def extreme_terms(g, op, iters, block, generator=None):
    """Block power iteration (warm-started in g['ext']) towards the stiffest and softest whitened modes of the student relative to the teacher;
    returns the divergence density of the Ritz values, mean(phi(ritz)) with phi(mu) = mu - log mu - 1, and the Ritz values themselves."""
    d = g['Rstar'].shape[0]
    if 'ext' not in g:
        V0_ = torch.randn(d, 2 * block, dtype=torch.float64, device=DEV, generator=generator)
        g['ext'] = (torch.linalg.qr(V0_[:, :block])[0], torch.linalg.qr(V0_[:, block:])[0])
    Vmax, Vmin = g['ext']
    with torch.no_grad():
        for _ in range(iters):
            Vmax = torch.linalg.qr(whiten_apply(g, op, Vmax))[0]; Vmin = torch.linalg.qr(whiten_solve(g, op, Vmin))[0]
    g['ext'] = (Vmax, Vmin)
    ritz = []
    for V in (Vmax, Vmin):
        H = V.T @ whiten_apply(g, op, V); ritz.append(torch.linalg.eigvalsh(0.5 * (H + H.T)))
    ritz = torch.cat(ritz)
    return (ritz - ritz.log() - 1.0).mean(), ritz


def action_error(g, op, z):
    ref = g['A'] @ z; pred = g['data'].quotient(op.apply(g['data'].quotient.lift(z)))
    return (pred - ref).square().sum(0) / ref.square().sum(0)


@torch.no_grad()
def evaluate_spectral(label, g, net, seed):
    """Probe-free metrics: exact divergence per mode (float32 trace), log-det gap, Ritz bounds on the extreme whitened modes, factor conditioning."""
    tick = sync()
    values, M = net(g, g['w'].log()); op = Operator(g, values, M)
    held = draw_probes_noA(g, 32, torch.Generator(device=DEV).manual_seed(seed + 2))
    res = dict(seat=label.seat, q=label.q, held_white=float(energy_error_ref(g, op, held).mean()))
    D, trace, gap, residual = divergence_terms(g, op, trace_dtype=g['ZT'].dtype)
    ge = dict(g); ge.pop('ext', None)
    _, ritz = extreme_terms(ge, op, 40, 8, torch.Generator(device=DEV).manual_seed(seed + 5))
    res.update(divergence_per_mode=float(D) / label.d, trace_per_mode=float(trace) / label.d, logdet_gap=float(gap), solve_residual=residual,
               mu_max_lower=float(ritz.max()), mu_min_upper=float(ritz.min()), **factor_conditioning(op))
    res['spectral_seconds'] = sync() - tick
    return res


def draw_probes_noA(g, white, generator):
    d = g['Rstar'].shape[0]; xi = torch.randn(d, white, dtype=torch.float64, device=DEV, generator=generator)
    return torch.linalg.solve_triangular(g['Rstar'], xi, upper=True)


def energy_error_ref(g, op, z):
    """Energy-metric error on whitened probes without the dense teacher: A z = R*^T (R* z)."""
    Rz = g['Rstar'] @ z; ref = g['Rstar'].T @ Rz; pred = g['data'].quotient(op.apply(g['data'].quotient.lift(z)))
    return torch.linalg.solve_triangular(g['Rstar'].T, pred - ref, upper=False).square().sum(0) / Rz.square().sum(0)


@torch.no_grad()
def evaluate_label(label, g, net, seed):
    """Legacy dense evaluation (materialized A_hat against the dense teacher A): probe metrics, e_A, mechanical directions."""
    tick = sync()
    values, M = net(g, g['w'].log()); op = Operator(g, values, M)
    held = draw_probes(g, 64, 32, torch.Generator(device=DEV).manual_seed(seed + 2))
